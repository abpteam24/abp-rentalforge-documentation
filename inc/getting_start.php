        <ol class="abrf-steps">
            <li>Install and activate WooCommerce, then complete its setup wizard.</li>
            <li>Install and activate <strong>ABP RentalForge</strong>. A new <strong>RentalForge</strong> menu appears in the admin sidebar.</li>
            <li>Open <strong>RentalForge → Status</strong> to see the setup checklist. <em>If the checklist is green you are ready to go.</em></li>
            <li>Go to <strong>RentalForge → Configuration → RentalForge</strong> and enter your site-wide defaults (currency labels, search layout, etc.).</li>
            <li>Create your first property under <strong>RentalForge → Properties</strong> — set a title, price, quantity and dates.</li>
            <li>Place the <code class="abrf-code">[abprf-booking]</code> shortcode on any page, or just open the property page — the booking form is ready.</li>
